def build_eval_report_prompt(request: str, context: str) -> str:
    return f"""
너는 머신러닝 모델 평가 보고서를 작성한다.

아래 문맥만 근거로 답하라.
문맥에 없는 내용은 절대 추측하지 말고 "문맥상 확인 불가"라고 써라.
이 문서는 공통적으로 성능표 페이지와 시각화 페이지로 구성된다.
성능표가 2개 이상이면 모델 비교를 우선하고,
시각화는 해당 페이지에 실제로 있는 모델에 대해서만 해석하라.
특정 feature 이름의 실제 생체역학적 의미를 임의로 추론하지 말라.
[Extracted Text]와 [Vision Extraction]이 충돌하면, 실제 페이지 시각 정보를 반영한 [Vision Extraction]을 우선하라.
하나의 페이지에 여러 시각화가 함께 존재할 수 있으므로, 페이지 전체를 하나의 그래프로 단순화하지 말고 각 시각 요소를 구분하여 해석하라.

[문맥]
{context}

[요청]
{request}

[출력 형식]
1. 평가 대상 개요
2. 정량 지표 요약
3. 모델 간 비교
4. 그래프 기반 해석
5. 설명가능성 해석
6. 종합 판단

[추가 규칙]
- 절대 볼드체를 사용하거나 '*'을 답변에 사용하지 말것.
- 수치는 문맥에 있는 값만 그대로 사용
- confusion matrix는 TN, FP, FN, TP 관점에서 해석
- ROC는 AUC와 좌상단 근접 여부 중심으로 해석
- PR은 recall 증가 시 precision 유지 여부 중심으로 해석
- calibration은 대각선 근접성 중심으로 해석
- LIME/SHAP는 feature 중요도만 설명하고 과도한 의미 해석 금지
- 시각화가 한 모델에만 존재하면 그 사실을 명시할 것
- [Vision Extraction]에서 숫자, 모델명, feature 이름이 추출되었으면 이를 우선 반영할 것
- boxplot 또는 기타 통계 시각화가 있으면, 분포 차이·중앙값·이상치 여부를 보이는 범위 내에서만 간단히 요약할 것

답변:
""".strip()